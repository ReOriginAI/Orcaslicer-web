for (const viewport of [{ width: 1440, height: 700 }, { width: 768, height: 800 }, { width: 390, height: 844 }]) {
  test(`full settings and long model names remain readable at ${viewport.width}px`, async ({ page }) => {
    await page.setViewportSize(viewport);
    await page.route('**/api/about', route => route.fulfill({ json: { slicerAvailable: true, orcaVersion: '2.4.2', supportedFormats: ['stl'], maxUploadMb: 250 } }));
    const machineId = 'printer', processId = 'process', filamentId = 'filament';
    await page.route('**/api/presets', route => route.fulfill({ json: {
      defaults: { machineId, processId, filamentId },
      machines: [{ id: machineId, name: 'Creality Ender-3 V3 KE 0.4 nozzle', compatibleMachineIds: [], nozzleDiameter: 0.4, buildVolume: { width: 220, depth: 220, height: 245 } }],
      processes: [{ id: processId, name: '0.20mm Standard @Creality Ender3V3KE', compatibleMachineIds: [machineId] }],
      filaments: [{ id: filamentId, name: 'Creality Generic PLA @Ender-3V3-all', compatibleMachineIds: [machineId] }],
    } }));
    await page.goto('/');
    const name = 'a-long-model-name-with-several-words-and-dimensions-220x220-final-version.stl';
    await page.getByTestId('model-upload').setInputFiles({ name, mimeType: 'model/stl', buffer: await readFile(resolve('fixtures/cube-20mm.stl')) });
    await expect(page.getByTestId('model-preview')).toHaveAttribute('data-loaded', 'true');
    for (const label of ['Infill pattern', 'Support placement']) {
      const field = page.getByRole('combobox', { name: label, exact: true });
      await field.scrollIntoViewIfNeeded();
      await expect(field).toBeInViewport();
      await field.click({ trial: true });
    }
    await page.getByRole('tab', { name: 'Advanced', exact: true }).click();
    await page.getByRole('checkbox', { name: 'Custom print settings' }).check();
    for (const label of ['Layer height', 'Retraction length', 'Brim']) {
      const field = page.getByLabel(label, { exact: true });
      await field.scrollIntoViewIfNeeded();
      await expect(field).toBeInViewport();
    }
    const layout = await page.evaluate(() => {
      const settings = document.querySelector('.settings-panel')!;
      const labels = [...document.querySelectorAll('.model-file-info strong, .slice-bar strong, .selected-preset')];
      return {
        overflow: document.documentElement.scrollWidth > window.innerWidth,
        clippedSettings: settings.scrollHeight > settings.clientHeight + 1,
        clippedLabels: labels.some(element => element.scrollWidth > element.clientWidth + 1),
        shortenedLabels: labels.some(element => getComputedStyle(element).textOverflow === 'ellipsis'),
      };
    });
    await page.screenshot({ path: test.info().outputPath('layout.png'), fullPage: true });
    expect(layout).toEqual({ overflow: false, clippedSettings: false, clippedLabels: false, shortenedLabels: false });
    await page.getByRole('tab', { name: 'Basic', exact: true }).click();
    await page.getByRole('combobox', { name: 'Supports', exact: true }).selectOption('false');
    await expect(page.getByRole('combobox', { name: 'Support type', exact: true })).toBeDisabled();
    await expect(page.getByRole('combobox', { name: 'Support placement', exact: true })).toBeDisabled();
  });
}
