import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
import {afterEach,beforeEach,describe,it,expect} from 'vitest';
import {validateOutput} from '../src/orca/result.js';
import {machineName} from './fixtures.js';
let dir:string;
beforeEach(async()=>{dir=await fs.mkdtemp(path.join(os.tmpdir(),'orca-result-'));});
afterEach(async()=>{await fs.rm(dir,{recursive:true,force:true});});
const gcode=(name:string)=>`; generated by OrcaSlicer 2.4.2\nG1 X110 Y110 E1\n; printer_settings_id = ${name}\n`;
describe('G-code result validation',()=>{
 it('accepts nonempty Orca G-code only when selected printer matches',async()=>{
  await fs.writeFile(path.join(dir,'plate_1.gcode'),gcode(machineName));const result=await validateOutput(dir,machineName,randomUUID(),'2.4.2',1.5);
  expect(result.files).toHaveLength(1);expect(result.printerName).toBe(machineName);expect(result.files[0]!.size).toBeGreaterThan(0);
 });
 it('refuses G-code targeting another machine',async()=>{
  await fs.writeFile(path.join(dir,'plate_1.gcode'),gcode('Unexpected printer'));
  await expect(validateOutput(dir,machineName,randomUUID(),'2.4.2',1)).rejects.toThrow('does not match');
 });
 it('refuses empty output and non-G-code diagnostic files',async()=>{
  await fs.writeFile(path.join(dir,'result.json'),'{}');await expect(validateOutput(dir,machineName,randomUUID(),'2.4.2',1)).rejects.toThrow('did not produce');
  await fs.writeFile(path.join(dir,'plate_1.gcode'),'');await expect(validateOutput(dir,machineName,randomUUID(),'2.4.2',1)).rejects.toThrow('empty');
 });
});
